/**
 * Minimal Android adapter for the embedded sing-box runtime.
 * This service only runs profiles generated by DoubleHopConfigBuilder.
 */
internal class DoubleHopPlatform(private val vpn: DoubleHopVpnService) : PlatformInterface {
    private val defaultMonitorLock = Any()
    @Volatile private var defaultNetworkCallback: ConnectivityManager.NetworkCallback? = null
    @Volatile private var defaultInterfaceListener: InterfaceUpdateListener? = null

    override fun localDNSTransport(): LocalDNSTransport? = null

    override fun usePlatformAutoDetectInterfaceControl(): Boolean = true

    override fun autoDetectInterfaceControl(fd: Int) {
        if (!vpn.protect(fd)) {
            throw IllegalStateException("无法保护双跳隧道底层套接字，已阻止可能的 VPN 路由环路")
        }
    }

    override fun openTun(options: TunOptions): Int {
        LogManager.info("DoubleHopPlatform", "sing-box 请求建立 Android TUN")
        if (VpnService.prepare(vpn) != null) {
            LogManager.error("DoubleHopPlatform", "建立 TUN 失败：缺少 VPN 授权")
            error("缺少 VPN 授权")
        }
        val builder = vpn.Builder()
            .setSession("WireOpen 双跳")
            .setMtu(if (options.mtu > 0) options.mtu else 1400)

        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
            builder.setMetered(false)
        }

        var hasV4 = false
        var hasV6 = false
        val ipv4Addresses = options.inet4Address
        while (ipv4Addresses.hasNext()) {
            val address = ipv4Addresses.next()
            builder.addAddress(address.address(), address.prefix())
            hasV4 = true
        }
        val ipv6Addresses = options.inet6Address
        while (ipv6Addresses.hasNext()) {
            val address = ipv6Addresses.next()
            builder.addAddress(address.address(), address.prefix())
            hasV6 = true
        }

        if (options.autoRoute) {
            if (options.dnsMode.value != Libbox.DNSModeDisabled) {
                val dns = options.dnsServerAddress
                while (dns.hasNext()) {
                    builder.addDnsServer(dns.next())
                }
            }
            // The generated double-hop profile intentionally routes all IPv4/IPv6 traffic.
            if (hasV4) builder.addRoute("0.0.0.0", 0)
            if (hasV6) builder.addRoute("::", 0)

            val includePackages = options.includePackage
            while (includePackages.hasNext()) {
                runCatching { builder.addAllowedApplication(includePackages.next()) }
            }
            val excludePackages = options.excludePackage
            while (excludePackages.hasNext()) {
                runCatching { builder.addDisallowedApplication(excludePackages.next()) }
            }
        }

        LogManager.info("DoubleHopPlatform", "Android TUN 路由参数已设置，正在调用 establish()")
        val pfd = builder.establish() ?: run {
            LogManager.error("DoubleHopPlatform", "Android Builder.establish() 返回空接口")
            error("Android 未能建立双跳 TUN 接口")
        }
        vpn.setTunDescriptor(pfd)
        LogManager.info("DoubleHopPlatform", "Android TUN 已建立，fd=${pfd.fd}")
        return pfd.fd
    }

    override fun useProcFS(): Boolean = Build.VERSION.SDK_INT < Build.VERSION_CODES.Q

    override fun findConnectionOwner(
        ipProtocol: Int,
        sourceAddress: String,
        sourcePort: Int,
        destinationAddress: String,
        destinationPort: Int,
    ): ConnectionOwner {
        val owner = ConnectionOwner()
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
            val cm = vpn.getSystemService(Context.CONNECTIVITY_SERVICE) as ConnectivityManager
            val uid = runCatching {
                cm.getConnectionOwnerUid(
                    ipProtocol,
                    InetSocketAddress(sourceAddress, sourcePort),
                    InetSocketAddress(destinationAddress, destinationPort),
                )
            }.getOrDefault(-1)
            if (uid >= 0) owner.userId = uid
        }
        return owner
    }

    override fun startDefaultInterfaceMonitor(listener: InterfaceUpdateListener) {
        val cm = vpn.getSystemService(Context.CONNECTIVITY_SERVICE) as ConnectivityManager
        synchronized(defaultMonitorLock) {
            defaultNetworkCallback?.let { old ->
                runCatching { cm.unregisterNetworkCallback(old) }
            }
            defaultInterfaceListener = listener

            val callback = object : ConnectivityManager.NetworkCallback() {
                override fun onAvailable(network: Network) {
                    publishDefaultInterface(listener, cm, network)
                }

                override fun onLost(network: Network) {
                    val active = runCatching { cm.activeNetwork }.getOrNull()
                        .takeIf { it != network }
                    publishDefaultInterface(listener, cm, active)
                }

                override fun onCapabilitiesChanged(
                    network: Network,
                    networkCapabilities: NetworkCapabilities,
                ) {
                    publishDefaultInterface(listener, cm, network)
                }

                override fun onLinkPropertiesChanged(network: Network, linkProperties: LinkProperties) {
                    publishDefaultInterface(listener, cm, network)
                }
            }
            defaultNetworkCallback = callback

            // Publish synchronously before DNS transports initialize.
            publishDefaultInterface(listener, cm, runCatching { cm.activeNetwork }.getOrNull())
            try {
                cm.registerDefaultNetworkCallback(callback)
                publishDefaultInterface(listener, cm, runCatching { cm.activeNetwork }.getOrNull())
                LogManager.info("DoubleHopPlatform", "sing-box 默认网络接口监听已启动")
            } catch (e: Exception) {
                defaultNetworkCallback = null
                LogManager.error(
                    "DoubleHopPlatform",
                    "注册默认网络监听失败：" + (e.message ?: e.javaClass.simpleName),
                )
            }
        }
    }

    override fun closeDefaultInterfaceMonitor(listener: InterfaceUpdateListener) {
        synchronized(defaultMonitorLock) {
            if (defaultInterfaceListener !== listener) return
            val cm = vpn.getSystemService(Context.CONNECTIVITY_SERVICE) as ConnectivityManager
            val callback = defaultNetworkCallback
            defaultNetworkCallback = null
            defaultInterfaceListener = null
            if (callback != null) {
                runCatching { cm.unregisterNetworkCallback(callback) }
                    .onFailure {
                        LogManager.debug(
                            "DoubleHopPlatform",
                            "默认网络监听注销时返回：" + (it.message ?: "回调已注销"),
                        )
                    }
            }
        }
    }

    internal fun shutdown() {
        synchronized(defaultMonitorLock) {
            val cm = vpn.getSystemService(Context.CONNECTIVITY_SERVICE) as ConnectivityManager
            val callback = defaultNetworkCallback
            defaultNetworkCallback = null
            defaultInterfaceListener = null
            if (callback != null) {
                runCatching { cm.unregisterNetworkCallback(callback) }
                    .onFailure {
                        LogManager.debug(
                            "DoubleHopPlatform",
                            "强制释放默认网络监听：" + (it.message ?: "回调已注销"),
                        )
                    }
            }
        }
    }

    private fun publishDefaultInterface(
        listener: InterfaceUpdateListener,
        cm: ConnectivityManager,
        preferredNetwork: Network?,
    ) {
        val network = findPhysicalNetwork(cm, preferredNetwork)
        val properties = network?.let { runCatching { cm.getLinkProperties(it) }.getOrNull() }
        val name = properties?.interfaceName
        val index = if (name.isNullOrBlank()) {
            -1
        } else {
            runCatching { SystemNetworkInterface.getByName(name)?.index ?: -1 }.getOrDefault(-1)
        }

        if (name.isNullOrBlank() || index <= 0) {
            runCatching { listener.updateDefaultInterface("", -1, false, false) }
            LogManager.warn("DoubleHopPlatform", "尚未识别到可用的底层默认网络接口")
            return
        }

        val capabilities = network?.let { runCatching { cm.getNetworkCapabilities(it) }.getOrNull() }
        val expensive = capabilities?.hasCapability(NetworkCapabilities.NET_CAPABILITY_NOT_METERED) != true
        runCatching { listener.updateDefaultInterface(name, index, expensive, false) }
            .onSuccess {
                LogManager.debug("DoubleHopPlatform", "默认底层网络接口已更新：$name (index=$index)")
            }
            .onFailure {
                LogManager.warn(
                    "DoubleHopPlatform",
                    "通知 sing-box 更新默认接口失败：" + (it.message ?: it.javaClass.simpleName),
                )
            }
    }

    private fun findPhysicalNetwork(cm: ConnectivityManager, preferredNetwork: Network?): Network? {
        fun isUsable(network: Network): Boolean {
            val capabilities = runCatching { cm.getNetworkCapabilities(network) }.getOrNull() ?: return false
            if (capabilities.hasTransport(NetworkCapabilities.TRANSPORT_VPN)
                || !capabilities.hasCapability(NetworkCapabilities.NET_CAPABILITY_INTERNET)
            ) return false
            val name = runCatching { cm.getLinkProperties(network)?.interfaceName }.getOrNull()
                ?: return false
            return runCatching { SystemNetworkInterface.getByName(name)?.index ?: -1 }.getOrDefault(-1) > 0
        }

        if (preferredNetwork != null && isUsable(preferredNetwork)) return preferredNetwork

        // If Android reports a VPN interface as active, prefer networks declared underneath it.
        val underlying = runCatching { vpn.underlyingNetworks }.getOrNull().orEmpty()
        underlying.firstOrNull(::isUsable)?.let { return it }

        val candidates = runCatching { cm.allNetworks.toList() }.getOrDefault(emptyList())
            .filter(::isUsable)
        return candidates.maxWithOrNull(
            compareBy<Network> {
                runCatching {
                    cm.getNetworkCapabilities(it)
                        ?.hasCapability(NetworkCapabilities.NET_CAPABILITY_VALIDATED) == true
                }.getOrDefault(false)
            }.thenBy {
                runCatching {
                    cm.getNetworkCapabilities(it)
                        ?.hasCapability(NetworkCapabilities.NET_CAPABILITY_NOT_METERED) == true
                }.getOrDefault(false)
            },
        )
    }

    override fun getInterfaces(): NetworkInterfaceIterator {
        val result = mutableListOf<BoxNetworkInterface>()
        val cm = vpn.getSystemService(Context.CONNECTIVITY_SERVICE) as ConnectivityManager
        val systemInterfaces = runCatching {
            Collections.list(SystemNetworkInterface.getNetworkInterfaces())
        }.getOrDefault(emptyList())
        for (network in cm.allNetworks) {
            val properties = cm.getLinkProperties(network) ?: continue
            val capabilities = cm.getNetworkCapabilities(network) ?: continue
            val name = properties.interfaceName ?: continue
            val systemInterface = systemInterfaces.firstOrNull { it.name == name } ?: continue
            val item = BoxNetworkInterface()
            item.name = name
            item.index = systemInterface.index
            item.mtu = runCatching { systemInterface.mtu }.getOrDefault(0)
            item.dnsServer = StringArray(properties.dnsServers.mapNotNull { it.hostAddress }.iterator())
            item.gateway = StringArray(
                properties.routes.filter { it.destination.prefixLength == 0 }
                    .mapNotNull { it.gateway }
                    .filterNot { it.isAnyLocalAddress }
                    .mapNotNull { it.hostAddress }.iterator(),
            )
            item.addresses = StringArray(systemInterface.interfaceAddresses.map { it.toPrefix() }.iterator())
            item.type = when {
                capabilities.hasTransport(NetworkCapabilities.TRANSPORT_WIFI) -> Libbox.InterfaceTypeWIFI
                capabilities.hasTransport(NetworkCapabilities.TRANSPORT_CELLULAR) -> Libbox.InterfaceTypeCellular
                capabilities.hasTransport(NetworkCapabilities.TRANSPORT_ETHERNET) -> Libbox.InterfaceTypeEthernet
                else -> Libbox.InterfaceTypeOther
            }
            item.metered = !capabilities.hasCapability(NetworkCapabilities.NET_CAPABILITY_NOT_METERED)
            var flags = 0
            if (capabilities.hasCapability(NetworkCapabilities.NET_CAPABILITY_INTERNET)) {
                flags = flags or OsConstants.IFF_UP or OsConstants.IFF_RUNNING
            }
            if (systemInterface.isLoopback) flags = flags or OsConstants.IFF_LOOPBACK
            if (systemInterface.isPointToPoint) flags = flags or OsConstants.IFF_POINTOPOINT
            if (systemInterface.supportsMulticast()) flags = flags or OsConstants.IFF_MULTICAST
            item.flags = flags
            result.add(item)
        }
        return InterfaceArray(result.iterator())
    }

    override fun underNetworkExtension(): Boolean = false
    override fun includeAllNetworks(): Boolean = false
    override fun clearDNSCache() {}
    override fun readWIFIState(): WIFIState? = null
    override fun sendNotification(notification: io.nekohasekai.libbox.Notification) {}
    override fun cancelNotification(identifier: String, typeID: Int) {}
    override fun startNeighborMonitor(listener: NeighborUpdateListener?) {}
    override fun closeNeighborMonitor(listener: NeighborUpdateListener?) {}
    override fun registerMyInterface(name: String?) {}
    override fun usePlatformShell(): Boolean = false
    override fun checkPlatformShell() { error("双跳服务不启用系统 Shell") }
    override fun openShellSession(
        user: PlatformUser?,
        command: String?,
        environ: StringIterator?,
        term: String?,
        rows: Int,
        cols: Int,
    ): ShellSession = error("双跳服务不启用系统 Shell")
    override fun lookupUser(username: String?): PlatformUser = error("双跳服务不启用用户解析")
    override fun lookupSFTPServer(): String = error("双跳服务不启用 SFTP")
    override fun readSystemSSHHostKey(): String = error("双跳服务不启用 SSH")
    override fun tailscaleHostname(): String = "WireOpen"
    override fun usePlatformBridge(): Boolean = false
    override fun createBridge(options: BridgeOptions?): BridgeSession = error("双跳服务不支持系统桥接")

    private fun InterfaceAddress.toPrefix(): String {
        val address = address ?: return ""
        return if (address is Inet6Address) {
            "${address.hostAddress}/${networkPrefixLength}"
        } else {
            "${address.hostAddress}/${networkPrefixLength}"
        }
    }

    private class StringArray(values: Iterator<String>) : StringIterator {
        private val items = values.asSequence().toList()
        private var index = 0
        override fun len(): Int = items.size
        override fun hasNext(): Boolean = index < items.size
        override fun next(): String = items[index++]
    }

    private class InterfaceArray(private val values: Iterator<BoxNetworkInterface>) : NetworkInterfaceIterator {
        override fun hasNext(): Boolean = values.hasNext()
        override fun next(): BoxNetworkInterface = values.next()
    }
}
